/*
 * usart.c  -  USART1 for the GPS module (u-blox NEO-6M, NMEA @ 9600 8N1).
 *
 * PA9/PA10 are already put in AF7 (USART1) mode by MX_GPIO_Init() in main.c,
 * so here we enable the USART1 clock, configure the block, and turn on the
 * USART1 receive interrupt.  Bytes are handed to lwgps in
 * HAL_UART_RxCpltCallback() (see sensors.c).
 */
#include "usart.h"

UART_HandleTypeDef huart1;

void MX_USART1_UART_Init(void)
{
  __HAL_RCC_USART1_CLK_ENABLE();

  huart1.Instance          = USART1;
  huart1.Init.BaudRate     = 9600;                 /* NEO-6M default */
  huart1.Init.WordLength   = UART_WORDLENGTH_8B;
  huart1.Init.StopBits     = UART_STOPBITS_1;
  huart1.Init.Parity       = UART_PARITY_NONE;
  huart1.Init.Mode         = UART_MODE_TX_RX;
  huart1.Init.HwFlowCtl    = UART_HWCONTROL_NONE;
  huart1.Init.OverSampling = UART_OVERSAMPLING_16;
  if (HAL_UART_Init(&huart1) != HAL_OK)
  {
    Error_Handler();
  }

  /* Enable the USART1 global interrupt for byte-by-byte NMEA reception */
  HAL_NVIC_SetPriority(USART1_IRQn, 5, 0);
  HAL_NVIC_EnableIRQ(USART1_IRQn);
}

/*
 * USART1 interrupt entry point.  Not generated by CubeMX (USART1 is not an
 * enabled peripheral in the .ioc), so we provide it here; it overrides the
 * weak Default_Handler from the startup file.
 */
void USART1_IRQHandler(void)
{
  HAL_UART_IRQHandler(&huart1);
}
